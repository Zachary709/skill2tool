import { promises as fs } from "node:fs";
import * as path from "node:path";
import type { ExternalServiceSpec } from "./plan.ts";
import { atomicWrite } from "./artifacts.ts";

interface RegistryEntry {
	name: string;
	description?: string;
	kind?: string;
	unit?: string;
	checks?: Record<string, unknown>;
	commands?: Record<string, string>;
	policy?: Record<string, unknown>;
	generatedBy?: string;
	tools?: string[];
	[key: string]: unknown;
}

interface RegistryFile {
	version?: number;
	services?: RegistryEntry[];
	[key: string]: unknown;
}

function commandsFor(unit: string): Record<string, string> {
	return {
		status: `systemctl --user is-active ${unit}`,
		detail: `systemctl --user status ${unit} --no-pager --lines=0`,
		start: `systemctl --user start ${unit}`,
		restart: `systemctl --user restart ${unit}`,
		logs: `journalctl --user -u ${unit} -n 60 --no-pager`,
	};
}

async function readRegistry(registryPath: string): Promise<RegistryFile> {
	try {
		const raw = JSON.parse(await fs.readFile(registryPath, "utf8")) as RegistryFile;
		return raw && typeof raw === "object" ? raw : { version: 1, services: [] };
	} catch (error) {
		if ((error as NodeJS.ErrnoException).code === "ENOENT") return { version: 1, services: [] };
		throw error;
	}
}

/**
 * Register external service dependencies of a generated tool. The registry is
 * the file service_keeper reads. A manually maintained entry is never
 * overwritten; an entry generated by an earlier tool_add run is merged.
 */
export async function registerExternalServices(
	agentDir: string,
	toolName: string,
	specs: ExternalServiceSpec[],
): Promise<{ added: string[]; updated: string[]; preserved: string[]; errors: string[] }> {
	const result = { added: [] as string[], updated: [] as string[], preserved: [] as string[], errors: [] as string[] };
	if (specs.length === 0) return result;
	const registryPath = path.join(agentDir, "services", "registry.json");
	let registry: RegistryFile;
	try {
		registry = await readRegistry(registryPath);
	} catch (error) {
		result.errors.push(`failed to read ${registryPath}: ${String(error)}`);
		return result;
	}
	const services = Array.isArray(registry.services) ? registry.services : [];
	let changed = false;
	for (const spec of specs) {
		const byName = services.find((entry) => entry.name === spec.name);
		const existing = byName ?? services.find((entry) => entry.unit === spec.unit);
		if (existing && existing.generatedBy !== "tool_add") {
			existing.tools = Array.from(new Set([...(existing.tools ?? []), toolName]));
			result.preserved.push(existing.name);
			changed = true;
			continue;
		}
		const entry: RegistryEntry = {
			name: spec.name,
			description: spec.description,
			kind: "systemd-user",
			unit: spec.unit,
			checks: spec.checks ?? {},
			commands: commandsFor(spec.unit),
			policy: {
				cooldownSeconds: spec.policy?.cooldownSeconds ?? 120,
				maxActionsPerDay: spec.policy?.maxActionsPerDay ?? 3,
				waitSeconds: spec.policy?.waitSeconds ?? 45,
			},
			generatedBy: "tool_add",
			tools: Array.from(new Set([...(existing?.tools ?? []), toolName])),
		};
		if (existing) {
			Object.assign(existing, entry, { name: existing.name, tools: Array.from(new Set([...(existing.tools ?? []), toolName])) });
			result.updated.push(existing.name);
			changed = true;
		} else {
			services.push(entry);
			result.added.push(spec.name);
			changed = true;
		}
	}
	if (!changed) return result;
	const next: RegistryFile = { ...registry, version: registry.version ?? 1, services };
	await atomicWrite(registryPath, `${JSON.stringify(next, null, 2)}\n`);
	return result;
}
